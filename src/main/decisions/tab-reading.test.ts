import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { tmpdir } from 'node:os'
import { cleanHumanText, pathsUnder, readTab, readTabLines } from './tab-reading'

// What a tab said and touched (PRDCT-5179), read from invented transcripts
// of the three harnesses, in the shapes the history's own tests use. Every
// person, project and path is invented.

const W = '/w'

const claudeLines = [
  {
    type: 'user',
    message: { content: 'Caveat: The messages below were generated by the user' },
    isMeta: true
  },
  {
    type: 'user',
    message: {
      content:
        '<command-message>lane</command-message>\n<command-name>/lane</command-name>\n<command-args>quill 42</command-args>'
    }
  },
  {
    type: 'assistant',
    message: {
      content: [
        { type: 'text', text: 'Reading.' },
        { type: 'tool_use', name: 'Read', input: { file_path: '/w/labs/quill/web/app.ts' } },
        {
          type: 'tool_use',
          name: 'Bash',
          input: { command: 'ls /w/labs/quill/web /w/labs/atlas, /tmp/x' }
        }
      ]
    }
  },
  {
    type: 'user',
    toolUseResult: { stdout: 'x' },
    message: {
      content: [{ type: 'tool_result', content: '/w/labs/lumen/listed-by-a-tool.ts' }]
    }
  },
  {
    type: 'user',
    message: {
      content: [
        {
          type: 'text',
          text: '<system-reminder>Injected context.</system-reminder>\nNow fix the toolbar.'
        }
      ]
    }
  },
  { type: 'user', message: { content: '[Request interrupted by user]' } },
  { type: 'user', isSidechain: true, message: { content: 'a subagent prompt' } },
  { type: 'user', message: { content: 'Second.' } },
  { type: 'user', message: { content: 'Third.' } },
  { type: 'user', message: { content: 'Fourth.' } },
  {
    type: 'assistant',
    isSidechain: true,
    message: {
      content: [{ type: 'tool_use', name: 'Read', input: { file_path: '/w/labs/side.ts' } }]
    }
  }
]

const codexLines = [
  { type: 'session_meta', payload: { id: 'thread-1', cwd: '/w/labs/atlas' } },
  {
    type: 'response_item',
    payload: {
      type: 'message',
      role: 'user',
      content: [{ type: 'input_text', text: '<environment_context>cwd</environment_context>' }]
    }
  },
  {
    type: 'response_item',
    payload: {
      type: 'message',
      role: 'user',
      content: [{ type: 'input_text', text: 'Map the Atlas tiles.' }]
    }
  },
  {
    type: 'response_item',
    payload: {
      type: 'function_call',
      name: 'shell',
      arguments: '{"cmd":["cat","/w/labs/atlas/tiles.ts"],"workdir":"/w/labs/atlas"}'
    }
  },
  {
    type: 'response_item',
    payload: {
      type: 'custom_tool_call',
      name: 'apply_patch',
      input: '*** Update File: /w/labs/atlas/tiles.ts\n@@'
    }
  },
  {
    type: 'response_item',
    payload: { type: 'function_call_output', output: '/w/labs/lumen/never-counted.ts' }
  },
  {
    type: 'response_item',
    payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: 'Thanks.' }] }
  }
]

const piLines = [
  { type: 'session', id: 'pi-1', cwd: '/w/labs/lumen' },
  {
    type: 'message',
    message: { role: 'user', content: [{ type: 'text', text: 'Light the Lumen page.' }] }
  },
  {
    type: 'message',
    message: {
      role: 'assistant',
      content: [{ type: 'toolCall', name: 'read', arguments: { path: '/w/labs/lumen/page.tsx' } }]
    }
  },
  {
    type: 'message',
    message: { role: 'toolResult', content: [{ type: 'text', text: '/w/labs/quill/no.ts' }] }
  }
]

const lines = (entries: unknown[]): string[] => entries.map((entry) => JSON.stringify(entry))

describe('readTabLines', () => {
  it('Claude: the first message, the three latest, the paths the tool calls named', async () => {
    expect(await readTabLines(lines(claudeLines), 'claude', W)).toEqual({
      firstMessage: '/lane quill 42',
      latestMessages: ['Second.', 'Third.', 'Fourth.'],
      touched: { '/w/labs/quill/web/app.ts': 1, '/w/labs/quill/web': 1, '/w/labs/atlas': 1 }
    })
  })

  it('Claude: a reminder removed leaves the message, a dropped one is not counted', async () => {
    const reading = await readTabLines(lines(claudeLines.slice(0, 6)), 'claude', W)
    expect(reading?.latestMessages).toEqual(['Now fix the toolbar.'])
  })

  it('Codex: the injected context dropped, the call arguments and the patch counted, never an output', async () => {
    expect(await readTabLines(lines(codexLines), 'codex', W)).toEqual({
      firstMessage: 'Map the Atlas tiles.',
      latestMessages: ['Thanks.'],
      touched: { '/w/labs/atlas/tiles.ts': 2, '/w/labs/atlas': 1 }
    })
  })

  it('Pi: the person, the tool call, never a tool result', async () => {
    expect(await readTabLines(lines(piLines), 'pi', W)).toEqual({
      firstMessage: 'Light the Lumen page.',
      latestMessages: [],
      touched: { '/w/labs/lumen/page.tsx': 1 }
    })
  })

  it('nothing said: null', async () => {
    expect(await readTabLines(lines([claudeLines[0], claudeLines[2]]), 'claude', W)).toBeNull()
    expect(await readTabLines(['not json', ''], 'claude', W)).toBeNull()
  })
})

describe('the pure readers', () => {
  it('renders a slash command as typed, removes the reminders', () => {
    expect(cleanHumanText('<command-name>/quill</command-name><command-args></command-args>')).toBe(
      '/quill'
    )
    expect(cleanHumanText('<command-name>atlas</command-name>')).toBe('/atlas')
    expect(cleanHumanText('a<system-reminder>x\ny</system-reminder> b')).toBe('a b')
  })

  it('finds the absolute paths strictly under the root, never a neighbour', () => {
    expect(pathsUnder('cat /w/a.ts /w /wx/b.ts "/w/c d" https://h/w/e', '/w')).toEqual([
      '/w/a.ts',
      '/w/c'
    ])
  })
})

describe('readTab', () => {
  let root: string
  beforeEach(() => {
    root = mkdtempSync(join(tmpdir(), 'clave-tab-reading-'))
  })
  afterEach(() => {
    vi.unstubAllEnvs()
    rmSync(root, { recursive: true, force: true })
  })

  const write = (file: string, entries: unknown[]): void => {
    mkdirSync(join(file, '..'), { recursive: true })
    writeFileSync(file, lines(entries).join('\n') + '\n')
  }

  it('finds a Claude transcript under the tab account, as the history does', async () => {
    const configDir = join(root, 'claude')
    write(join(configDir, 'projects', '-w-labs-quill', 'conv-1.jsonl'), claudeLines)
    const reading = await readTab({
      harness: 'claude',
      cwd: '/w/labs/quill',
      conversationId: 'conv-1',
      configDir,
      workspaceRoot: W
    })
    expect(reading?.firstMessage).toBe('/lane quill 42')
  })

  it('finds a Codex rollout and a Pi session', async () => {
    vi.stubEnv('CLAVE_CODEX_ROOT', join(root, 'codex'))
    write(
      join(root, 'codex', '2026', '11', '25', 'rollout-2026-11-25T10-00-00-thread-1.jsonl'),
      codexLines
    )
    expect(
      (
        await readTab({
          harness: 'codex',
          cwd: '/w/labs/atlas',
          conversationId: 'thread-1',
          workspaceRoot: W
        })
      )?.firstMessage
    ).toBe('Map the Atlas tiles.')
    vi.stubEnv('PI_CODING_AGENT_DIR', join(root, 'pi'))
    write(
      join(root, 'pi', 'sessions', '--w-labs-lumen--', '2026-11-25T10-00-00_pi-1.jsonl'),
      piLines
    )
    expect(
      (
        await readTab({
          harness: 'pi',
          cwd: '/w/labs/lumen',
          conversationId: 'pi-1',
          workspaceRoot: W
        })
      )?.firstMessage
    ).toBe('Light the Lumen page.')
  })

  it('no transcript: null', async () => {
    expect(
      await readTab({
        harness: 'claude',
        cwd: '/w/nowhere',
        conversationId: 'missing',
        configDir: join(root, 'empty'),
        workspaceRoot: W
      })
    ).toBeNull()
  })
})
