/** The provider marks, by the component's name in cli-logos.tsx. */
export const LOGOS = {
  logo_antigravity: 'AntigravityLogo',
  logo_claude: 'ClaudeLogo',
  logo_codex: 'CodexLogo',
  logo_pi: 'PiLogo'
}

const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;')

function heroiconPaths(component) {
  const source = readFileSync(path.join(heroicons, '24', 'outline', 'esm', `${component}.js`), 'utf8')
  const paths = [...source.matchAll(/\bd: "([^"]+)"/g)].map((m) => m[1])
  if (!paths.length) throw new Error(`${component}: no path found`)
  return paths
}
function strokeDrawable(paths) {
  const body = paths
    .map(
      (d) =>
        `    <path\n        android:pathData="${esc(d)}"\n        android:strokeColor="#FFFFFFFF"\n        android:strokeWidth="1.5"\n        android:strokeLineCap="round"\n        android:strokeLineJoin="round"\n        android:fillColor="#00000000" />`
    )
    .join('\n')
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Heroicons 24/outline (MIT), generated by scripts/build-icons.mjs. Do not edit. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="24"\n    android:viewportHeight="24">\n${body}\n</vector>\n`
}
function logoDrawable(component) {
  const source = readFileSync(logos, 'utf8')
  const start = source.indexOf(`export function ${component}(`)
  if (start < 0) throw new Error(`${component}: not in cli-logos.tsx`)
  const end = source.indexOf('\nexport function', start + 1)
  const block = source.slice(start, end < 0 ? undefined : end)
  const viewBox = (/viewBox="([^"]+)"/.exec(block)?.[1] ?? '0 0 24 24').split(/\s+/).map(Number)
  const paths = [...block.matchAll(/<path([^>]*?)\/>/g)].map((m) => {
    const attrs = m[1]
    const d = /\bd="([^"]+)"/.exec(attrs)?.[1]
    const rule = /fillRule="([^"]+)"/.exec(attrs)?.[1]
    return `    <path\n        android:pathData="${esc(d)}"\n        android:fillColor="#FFFFFFFF"${rule === 'evenodd' ? '\n        android:fillType="evenOdd"' : ''} />`
  })
  if (!paths.length) throw new Error(`${component}: no path found`)
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- The provider mark of the desktop (cli-logos.tsx), generated by scripts/build-icons.mjs. Do not edit. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n    android:viewportWidth="${viewBox[2]}"\n    android:viewportHeight="${viewBox[3]}">\n${paths.join('\n')}\n</vector>\n`
}
let n = 0
for (const [name, component] of Object.entries(ICONS)) {
  writeFileSync(path.join(out, `ic_${name}.xml`), strokeDrawable(heroiconPaths(component)))
  n++
}
for (const [name, component] of Object.entries(LOGOS)) {
  writeFileSync(path.join(out, `ic_${name}.xml`), logoDrawable(component))
  n++
}
console.log(`wrote ${n} vector drawables to ${path.relative(process.cwd(), out)}`)
