// The phone's icons are the desktop's: Heroicons 24/outline read out of the very
// @heroicons/react modules the renderer imports (MIT, ui/LICENSES/MIT-Heroicons.txt), plus
// the four provider marks of apps/desktop/src/renderer/src/components/icons/cli-logos.tsx,
// each written as an Android vector drawable under ui/src/main/res/drawable/ic_<name>.xml,
// white, tinted at draw time the way the desktop paints currentColor. Run from the
// repository root with the root node_modules installed: node apps/mobile-android/scripts/build-icons.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, '..', '..', '..')
const require = createRequire(path.join(repo, 'package.json'))
const heroicons = path.dirname(require.resolve('@heroicons/react/package.json'))
const logos = path.join(repo, 'apps/desktop/src/renderer/src/components/icons/cli-logos.tsx')
const out = path.resolve(here, '..', 'ui', 'src', 'main', 'res', 'drawable')
mkdirSync(out, { recursive: true })

