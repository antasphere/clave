#!/usr/bin/env node
/* eslint-disable @typescript-eslint/explicit-function-return-type -- plain JS, run by npm run icons */
// The phone's icons are the desktop's: Heroicons 24/outline, read out of the
// very @heroicons/react modules the renderer imports, plus the three provider
// marks of apps/desktop/src/renderer/src/components/icons/cli-logos.tsx. The installed
// debug shell carries no SVG renderer, so each glyph is rasterised here with
// resvg at 1x, 2x and 3x (24, 48 and 72 px for a 24 dp box) in white and
// tinted at render time (`Icon`, src/ui/Icon.tsx), the way the desktop
// paints `currentColor`. The PNGs and the module naming them are committed;
// adding an icon is one name in ICONS below and a run of `npm run icons`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const { Resvg } = require('@resvg/resvg-js')
const heroicons = path.dirname(require.resolve('@heroicons/react/package.json'))
const logos = path.resolve(
  here,
  '..',
  '..',
  '..',
  'apps',
  'desktop',
  'src',
  'renderer',
  'src',
  'components',
  'icons',
  'cli-logos.tsx'
)
const out = path.resolve(here, '..', 'assets', 'icons')
const module_ = path.resolve(here, '..', 'src', 'ui', 'icons.generated.ts')
mkdirSync(out, { recursive: true })

/** phone name → Heroicons 24/outline component. */
