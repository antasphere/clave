/** The provider marks, by the component's name in cli-logos.tsx. */
export const LOGOS = {
  'logo-antigravity': 'AntigravityLogo',
  'logo-claude': 'ClaudeLogo',
  'logo-codex': 'CodexLogo',
  'logo-pi': 'PiLogo'
}

const SCALES = [1, 2, 3]
const BASE = 24

function heroiconSvg(component) {
  const source = readFileSync(
    path.join(heroicons, '24', 'outline', 'esm', `${component}.js`),
    'utf8'
  )
  const paths = [...source.matchAll(/\bd: "([^"]+)"/g)].map((m) => m[1])
  if (!paths.length) throw new Error(`${component}: no path found`)
  const body = paths.map((d) => `<path d="${d}"/>`).join('')
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="#ffffff" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`
}

function logoSvg(component) {
  const source = readFileSync(logos, 'utf8')
  const start = source.indexOf(`export function ${component}(`)
  if (start < 0) throw new Error(`${component}: not in cli-logos.tsx`)
  const end = source.indexOf('\nexport function', start + 1)
  const block = source.slice(start, end < 0 ? undefined : end)
  const viewBox = /viewBox="([^"]+)"/.exec(block)?.[1] ?? '0 0 24 24'
  const paths = [...block.matchAll(/<path([^>]*?)\/>/g)].map((m) => {
    const attrs = m[1]
    const d = /\bd="([^"]+)"/.exec(attrs)?.[1]
    const rule = /fillRule="([^"]+)"/.exec(attrs)?.[1]
    return `<path d="${d}" fill="#ffffff"${rule ? ` fill-rule="${rule}"` : ''}/>`
  })
  if (!paths.length) throw new Error(`${component}: no path found`)
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}">${paths.join('')}</svg>`
}

function render(name, svg) {
  for (const scale of SCALES) {
    const png = new Resvg(svg, { fitTo: { mode: 'width', value: BASE * scale } }).render().asPng()
    writeFileSync(path.join(out, `${name}${scale === 1 ? '' : `@${scale}x`}.png`), png)
  }
}

const names = [...Object.keys(ICONS), ...Object.keys(LOGOS)].sort()
for (const [name, component] of Object.entries(ICONS)) render(name, heroiconSvg(component))
for (const [name, component] of Object.entries(LOGOS)) render(name, logoSvg(component))

const lines = [
  '/* Generated by scripts/build-icons.mjs from @heroicons/react (24/outline) and',
  '   apps/desktop/src/renderer/src/components/icons/cli-logos.tsx. Do not edit: `npm run icons`',
  '   in apps/mobile rewrites it with the PNGs under assets/icons. */',
  '',
  '/* eslint-disable @typescript-eslint/no-require-imports -- the bundler reads the asset paths at build time */',
  'export const ICON_NAMES = [',
  names.map((n) => `  '${n}'`).join(',\n'),
  '] as const',
  'export type IconName = (typeof ICON_NAMES)[number]',
  '',
  'export const ICON_SOURCES: Record<IconName, number> = {',
  names
    .map((n) => `  ${/^[a-z]+$/.test(n) ? n : `'${n}'`}: require('../../assets/icons/${n}.png')`)
    .join(',\n'),
  '}',
  ''
]
writeFileSync(module_, lines.join('\n'))
console.log(
  `wrote ${names.length} icons × ${SCALES.length} scales to ${path.relative(process.cwd(), out)} and ${path.relative(process.cwd(), module_)}`
)
